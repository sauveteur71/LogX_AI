// ─── MIGRATION localStorage : ancien préfixe 'radiocontest_' (avant le
// renommage du produit en LogX AI) → 'logx_'. Sans ça, la config/les macros/
// le log déjà sauvegardés par l'utilisateur dans SON navigateur restent sous
// l'ancienne clé et semblent avoir disparu après la mise à jour. Idempotent
// (ne copie que si la nouvelle clé n'existe pas encore) — sans risque à
// exécuter depuis plusieurs pages/fichiers.
(function migrateRadioContestStorageKeys(){
  try{
    const toMigrate = [];
    for(let i = 0; i < localStorage.length; i++){
      const oldKey = localStorage.key(i);
      if(oldKey && oldKey.indexOf('radiocontest_') === 0) toMigrate.push(oldKey);
    }
    toMigrate.forEach(oldKey => {
      const newKey = 'logx_' + oldKey.slice('radiocontest_'.length);
      if(localStorage.getItem(newKey) === null){
        localStorage.setItem(newKey, localStorage.getItem(oldKey));
      }
    });
  }catch(e){}
})();

